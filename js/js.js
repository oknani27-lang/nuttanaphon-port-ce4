const imghtml = document.getElementById("imghtml");
imghtml.style.transition = "all 2s";
imghtml.addEventListener("mouseenter", function () {
  imghtml.style.transform = "scale(1.5)";
});

imghtml.addEventListener("mouseleave", function () {
  imghtml.style.transform = "scale(1.0)";
});

